// Helper function to get job resources for a career path
export function getJobResourcesForCareer(goalTitle) {
  const lowerGoal = goalTitle.toLowerCase();
  
  // Define more specific career matching
  const careerMappings = {
    'software engineer': ['software engineer', 'software developer', 'full stack', 'backend developer', 'frontend developer', 'web developer'],
    'data scientist': ['data scientist', 'machine learning engineer', 'ai engineer', 'ml engineer'],
    'web developer': ['web developer', 'frontend developer', 'full stack developer', 'react developer'],
    'mobile developer': ['mobile developer', 'android developer', 'ios developer', 'flutter developer', 'react native'],
    'devops engineer': ['devops engineer', 'devops', 'site reliability engineer', 'sre'],
    'machine learning engineer': ['machine learning engineer', 'ml engineer', 'ai engineer', 'deep learning'],
    'product manager': ['product manager', 'pm', 'product owner'],
    'ui ux designer': ['ui ux designer', 'ux designer', 'ui designer', 'product designer', 'interaction designer'],
    'cybersecurity analyst': ['cybersecurity', 'security analyst', 'security engineer', 'ethical hacker', 'penetration tester'],
    'cloud architect': ['cloud architect', 'cloud engineer', 'aws engineer', 'azure engineer', 'gcp engineer'],
    'data analyst': ['data analyst', 'business analyst', 'analytics'],
    'software testing': ['qa engineer', 'quality assurance', 'software tester', 'test engineer']
  };
  
  // Try to find match based on career mappings
  for (const [career, keywords] of Object.entries(careerMappings)) {
    for (const keyword of keywords) {
      if (lowerGoal.includes(keyword)) {
        return jobResources[career] || jobResources.default;
      }
    }
  }
  
  // Try direct keyword matching
  for (const [key, resources] of Object.entries(jobResources)) {
    if (key !== 'default' && lowerGoal.includes(key)) {
      return resources;
    }
  }
  
  // Dynamic fallback: generate role-specific search URLs using the goalTitle
  const encoded = encodeURIComponent(goalTitle);
  return [
    {
      type: 'job-board',
      title: `LinkedIn Jobs - ${goalTitle}`,
      description: `Search ${goalTitle} positions on LinkedIn`,
      url: `https://www.linkedin.com/jobs/search/?keywords=${encoded}`
    },
    {
      type: 'job-board',
      title: `Indeed - ${goalTitle} Jobs`,
      description: `${goalTitle} job listings on Indeed`,
      url: `https://www.indeed.com/jobs?q=${encoded}`
    },
    {
      type: 'job-board',
      title: `Glassdoor - ${goalTitle} Jobs`,
      description: `${goalTitle} jobs with salary information`,
      url: `https://www.glassdoor.com/Job/jobs.htm?sc.keyword=${encoded}`
    },
    {
      type: 'job-board',
      title: `Naukri.com - ${goalTitle}`,
      description: `${goalTitle} jobs in India`,
      url: `https://www.naukri.com/${encoded.replace(/%20/g, '-')}-jobs`
    },
    {
      type: 'remote',
      title: `Remote ${goalTitle} Jobs`,
      description: `Remote ${goalTitle} opportunities`,
      url: `https://remote.co/remote-jobs/search/?search_keywords=${encoded}`
    },
    {
      type: 'startup',
      title: `AngelList - ${goalTitle}`,
      description: `${goalTitle} jobs at startups`,
      url: `https://wellfound.com/jobs?q=${encoded}`
    }
  ];
}
